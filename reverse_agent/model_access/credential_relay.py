class _RelayHandler(BaseHTTPRequestHandler):
    manager: CredentialRelayManager
    upstream_timeout: float = 120.0

    server_version = "reverse-agent-relay/1"
    sys_version = ""

    def log_message(self, format: str, *args: object) -> None:
        return

    def do_POST(self) -> None:  # noqa: N802
        if not self._check_loopback():
            self._send_error(403, "relay_forbidden")
            return

        lease_id = self._extract_lease_id()
        if not lease_id:
            self._send_error(400, "missing_lease")
            return

        body = self._read_body()
        if body is None:
            self._send_error(400, "invalid_body")
            return

        request_path = urlsplit(self.path).path
        if request_path != "/chat/completions":
            self._send_error(404, "relay_route_not_found")
            return

        try:
            payload = json.loads(body.decode("utf-8"))
        except (json.JSONDecodeError, UnicodeDecodeError):
            self._send_error(400, "invalid_json")
            return
        if not isinstance(payload, dict):
            self._send_error(400, "invalid_json")
            return

        request_model = payload.get("model")
        try:
            active = self.manager._validate_lease_for_request(
                lease_id,
                method="POST",
                path="/chat/completions",
                model=request_model,
            )
        except CredentialRelayError:
            self._send_error(401, "lease_invalid")
            return

        try:
            accept = self.headers.get("Accept", "")
            if "text/event-stream" in accept:
                self._relay_sse_fail_closed(active, body)
                return
            status, response_body, _resp_headers = forward_to_upstream(
                active,
                body=body,
                timeout=self.upstream_timeout,
            )
        except CredentialRelayError:
            self._send_error(502, "upstream_error")
            return

        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(response_body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(response_body)

    def do_GET(self) -> None:  # noqa: N802
        if not self._check_loopback():
            self._send_error(403, "relay_forbidden")
            return
        if self.path == "/health":
            self._send_json(200, {"status": "relay_healthy"})
            return
        self._send_error(405, "relay_method_not_allowed")

    def _extract_lease_id(self) -> str | None:
        auth = self.headers.get("Authorization", "")
        if auth.lower().startswith("bearer "):
            token = auth[len("bearer "):].strip()
            if token:
                return token
        return None

    def _read_body(self) -> bytes | None:
        raw = self.headers.get("Content-Length")
        if raw is None:
            return b""
        try:
            length = int(raw)
        except (ValueError, TypeError):
            return None
        if length < 0 or length > _MAX_BODY_BYTES:
            return None
        return self.rfile.read(length)

    def _check_loopback(self) -> bool:
        addr = getattr(self, "client_address", None)
        if addr and isinstance(addr, tuple) and addr[0]:
            host = addr[0]
            try:
                address = ip_address(host)
                return address.is_loopback
            except ValueError:
                return host.lower() in ("localhost",)
        return False

    def _send_error(self, code: int, reason: str) -> None:
        body = json.dumps({"error": reason}, separators=(",", ":")).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _send_sanitized_error(self, code: int) -> None:
        body = json.dumps({"error": "upstream_error"}, separators=(",", ":")).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _relay_sse_fail_closed(self, active: _ActiveLease, body: bytes) -> None:
        _validate_upstream_url(active.snapshot.base_url)
        upstream_url = f"{active.snapshot.base_url}/chat/completions"
        headers = {
            "Authorization": f"Bearer {active.snapshot.resolved_api_key}",
            "Content-Type": "application/json",
            "Content-Length": str(len(body)),
            "Accept": "text/event-stream",
        }
        req = Request(upstream_url, data=body, headers=headers, method="POST")
        req.full_url = upstream_url
        try:
            with urlopen(req, timeout=self.upstream_timeout) as resp:  # noqa: S310
                status = int(resp.status)
                if status != 200:
                    self._send_sanitized_error(status)
                    return
                self.send_response(200)
                self.send_header("Content-Type", "text/event-stream")
                self.send_header("Cache-Control", "no-store")
                self.end_headers()
                while True:
                    chunk = resp.read(4096)
                    if not chunk:
                        break
                    self.wfile.write(chunk)
                    self.wfile.flush()
        except HTTPError as exc:
            self._send_sanitized_error(int(exc.code))
        except (URLError, TimeoutError, OSError):
            self._send_error(502, "upstream_error")

    def _send_json(self, code: int, payload: dict[str, Any]) -> None:
        body = json.dumps(payload, separators=(",", ":")).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


