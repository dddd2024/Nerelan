def _http_roundtrip(
    url: str,
    method: str,
    body: bytes,
    headers: dict[str, str],
    timeout: float,
) -> tuple[int, bytes, dict[str, str]]:
    req = Request(url, data=body, headers=headers, method=method)
    req.full_url = url
    try:
        with urlopen(req, timeout=timeout) as resp:  # noqa: S310 - gated relay
            status = int(resp.status)
            resp_headers = {k.lower(): v for k, v in resp.getheaders()}
            data = resp.read(_MAX_BODY_BYTES)
            return status, data, resp_headers
    except HTTPError as exc:
        body = exc.read(_MAX_BODY_BYTES)
        headers = {k.lower(): v for k, v in exc.headers.items()} if exc.headers else {}
        return int(exc.code), body, headers
    except (URLError, TimeoutError, OSError) as exc:
        raise CredentialRelayError(f"upstream_error:{exc.__class__.__name__}") from exc


def forward_to_upstream(
    active: _ActiveLease,
    *,
    body: bytes,
    timeout: float = 120.0,
) -> tuple[int, bytes, dict[str, str]]:
    """Inject provider Authorization and forward to the frozen upstream URL."""
    _validate_upstream_url(active.snapshot.base_url)
    upstream_url = f"{active.snapshot.base_url}/chat/completions"
    headers = {
        "Authorization": f"Bearer {active.snapshot.resolved_api_key}",
        "Content-Type": "application/json",
        "Content-Length": str(len(body)),
        "Accept": "application/json, text/event-stream",
    }
    return _http_roundtrip(upstream_url, "POST", body, headers, timeout)


# ---------------------------------------------------------------------------
# Streamed (SSE) relay
# ---------------------------------------------------------------------------

def stream_sse(
    active: _ActiveLease,
    *,
    body: bytes,
    wfile: Any,
    timeout: float = 120.0,
) -> int:
    """Forward request and relay raw SSE response directly to the client wfile.

    Pure passthrough: no fabricated status events, no extra [DONE], no
    newline injection, no payload transformation. The upstream stream is
    read in bounded chunks and flushed to the client in upstream order.
    """
    _validate_upstream_url(active.snapshot.base_url)
    upstream_url = f"{active.snapshot.base_url}/chat/completions"
    headers = {
        "Authorization": f"Bearer {active.snapshot.resolved_api_key}",
        "Content-Type": "application/json",
        "Content-Length": str(len(body)),
        "Accept": "text/event-stream",
    }
    req = Request(upstream_url, data=body, headers=headers, method="POST")
    req.full_url = upstream_url
    try:
        with urlopen(req, timeout=timeout) as resp:  # noqa: S310
            status = int(resp.status)
            chunk_size = 4096
            while True:
                chunk = resp.read(chunk_size)
                if not chunk:
                    break
                wfile.write(chunk)
                wfile.flush()
            return status
    except HTTPError as exc:
        return int(exc.code)
    except (URLError, TimeoutError, OSError) as exc:
        raise CredentialRelayError(f"upstream_error:{exc.__class__.__name__}") from exc


