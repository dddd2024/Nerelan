def _validate_loopback_url(value: str) -> None:
    parsed = urlsplit(value.strip())
    if parsed.scheme not in {"http", "https"}:
        raise CredentialRelayError("relay_url_invalid")
    host = (parsed.hostname or "").casefold()
    if host == "localhost":
        return
    try:
        address = ip_address(host)
    except ValueError:
        raise CredentialRelayError("relay_url_not_loopback")
    if not address.is_loopback:
        raise CredentialRelayError("relay_url_not_loopback")


def _validate_upstream_url(base_url: str) -> None:
    """Fail closed on non-loopback cleartext HTTP upstream URLs.

    HTTPS is allowed for any host. HTTP is only allowed for exact loopback
    addresses (127.0.0.1, ::1, localhost). No DNS resolution is performed;
    the boundary is determined purely from the URL hostname.
    """
    parsed = urlsplit(base_url.strip())
    if parsed.scheme == "https":
        return
    if parsed.scheme == "http":
        host = (parsed.hostname or "").casefold()
        if host == "localhost":
            return
        try:
            address = ip_address(host)
        except ValueError:
            raise CredentialRelayError("upstream_cleartext_not_loopback")
        if address not in {ip_address("127.0.0.1"), ip_address("::1")}:
            raise CredentialRelayError("upstream_cleartext_not_loopback")
        return
    raise CredentialRelayError("upstream_url_invalid")


def _normalize_model_id(provider: str, model_id: str) -> str:
    if "/" not in model_id:
        return f"{provider}/{model_id}"
    return model_id


def run_credential_relay_server(
    *,
    manager: CredentialRelayManager,
    host: str = "127.0.0.1",
    port: int = 0,
    upstream_timeout: float = 120.0,
) -> ThreadingHTTPServer:
    handler_cls = type(
        "_RelayHandler",
        (_RelayHandler,),
        {"manager": manager, "upstream_timeout": upstream_timeout},
    )
    server = ThreadingHTTPServer((host, port), handler_cls)
    return server


class CredentialRelayServer:
    """Context-managed relay server bound to a fresh loopback port."""

    def __init__(
        self,
        manager: CredentialRelayManager,
        *,
        host: str = "127.0.0.1",
        port: int = 0,
        upstream_timeout: float = 120.0,
    ) -> None:
        self.manager = manager
        self._host = host
        self._port = port
        self._upstream_timeout = upstream_timeout
        self._server: ThreadingHTTPServer | None = None
        self._thread: threading.Thread | None = None
        self.url = ""

    def __enter__(self) -> "CredentialRelayServer":
        self._server = run_credential_relay_server(
            manager=self.manager,
            host=self._host,
            port=self._port,
            upstream_timeout=self._upstream_timeout,
        )
        self._port = self._server.server_address[1]
        self.url = f"http://{self._host}:{self._port}"
        self._thread = threading.Thread(target=self._server.serve_forever, daemon=True)
        self._thread.start()
        return self

    def __exit__(self, exc_type, exc_val, exc_tb):  # noqa: N802,N803
        if self._server:
            self._server.shutdown()
        if self._thread:
            self._thread.join(timeout=3.0)
        return False